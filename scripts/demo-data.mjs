// Fills a local journal with made-up trades, for trying it out or taking
// screenshots. The trades are random; the prices are real one-minute NQ bars
// from Yahoo Finance, so the charts line up with them.
//
//   1. Run the journal locally:  npx wrangler dev
//   2. Sign in, open Settings, make an API key.
//   3. node scripts/demo-data.mjs http://localhost:8787 tj_your_key
//
// Only local addresses are accepted, so it cannot write made-up trades into a
// real journal by mistake.

const [base = 'http://localhost:8787', key] = process.argv.slice(2);
if (!key) { console.error('usage: node scripts/demo-data.mjs <local journal URL> <API key>'); process.exit(2); }
if (!/^http:\/\/(localhost|127\.0\.0\.1)(:\d+)?\/?$/.test(base)) { console.error('Only a local journal (http://localhost:...) is accepted.'); process.exit(2); }

let seed = 7;
const rand = () => { seed = (seed * 1664525 + 1013904223) % 4294967296; return seed / 4294967296 };
const pick = (a) => a[Math.floor(rand() * a.length)];

// One-minute NQ bars for the last few weeks. Yahoo keeps about 30 days of them
// and serves at most a week per request.
const now = Math.floor(Date.now() / 1000);
const bars = [];
for (let end = now; end > now - 28 * 86400; end -= 7 * 86400) {
  const res = await fetch(`https://query1.finance.yahoo.com/v8/finance/chart/NQ%3DF?interval=1m&period1=${end - 7 * 86400}&period2=${end}&includePrePost=true`,
    { headers: { 'user-agent': 'Mozilla/5.0' } });
  if (!res.ok) { console.error(`Yahoo Finance answered ${res.status}; try again later.`); process.exit(1); }
  const r = (await res.json()).chart.result[0];
  if (!r.timestamp) continue;
  r.timestamp.forEach((t, i) => { const c = r.indicators.quote[0].close[i]; if (c != null) bars.push({ t, c }); });
}
bars.sort((x, y) => x.t - y.t);
const byMin = new Map(bars.map((b) => [b.t - (b.t % 60), b.c]));

const et = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/New_York', year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', hour12: false });
const parts = (t) => Object.fromEntries(et.formatToParts(new Date(t * 1000)).map((p) => [p.type, p.value]));
const days = new Map();
for (const b of bars) {
  const p = parts(b.t);
  const mins = (+p.hour % 24) * 60 + +p.minute;
  if (mins >= 9 * 60 + 30 && mins < 11 * 60 + 30) {
    const d = `${p.year}-${p.month}-${p.day}`;
    if (!days.has(d)) days.set(d, []);
    days.get(d).push(b.t - (b.t % 60));
  }
}

const iso = (t) => new Date(t * 1000).toISOString().replace('.000Z', 'Z');
const tick = (x) => Math.round(x * 4) / 4;
let sent = 0;
for (const [date, minutes] of [...days.entries()].slice(-15)) {
  const fills = [];
  let t = minutes[0] + Math.floor(rand() * 10) * 60;
  const end = minutes[minutes.length - 1];
  const count = 3 + Math.floor(rand() * 6);
  for (let i = 0; i < count && t < end - 30 * 60; i++) {
    const side = rand() < 0.55 ? 'buy' : 'sell';
    const exitSide = side === 'buy' ? 'sell' : 'buy';
    const clip = pick([1, 2, 2, 3]);
    const adds = rand() < 0.4 ? 1 : 0;
    let at = t + Math.floor(rand() * 50);
    for (let a = 0; a <= adds; a++) {
      const px = byMin.get(at - (at % 60)) ?? byMin.get(t);
      fills.push({ time: iso(at), side, qty: clip, price: tick(px + (rand() - 0.5) * 2), instrument: 'MNQZ6' });
      at += 40 + Math.floor(rand() * 120);
    }
    const hold = 120 + Math.floor(rand() * 720);
    const out = at + hold;
    const total = clip * (adds + 1);
    const first = Math.ceil(total / 2);
    const px1 = byMin.get(out - (out % 60) - 60) ?? byMin.get(t);
    const px2 = byMin.get(out - (out % 60)) ?? px1;
    fills.push({ time: iso(out - 60), side: exitSide, qty: first, price: tick(px1), instrument: 'MNQZ6' });
    if (total - first) fills.push({ time: iso(out), side: exitSide, qty: total - first, price: tick(px2), instrument: 'MNQZ6' });
    t = out + 120 + Math.floor(rand() * 900);
  }
  const body = { date, platform: 'demo', account: 'DEMO-1', raw_log: 'Generated by scripts/demo-data.mjs', fills };
  const resp = await fetch(`${base.replace(/\/$/, '')}/ingest/v1/day`, {
    method: 'POST', headers: { 'content-type': 'application/json', 'x-api-key': key }, body: JSON.stringify(body),
  });
  const j = await resp.json();
  if (!resp.ok) { console.error(date, j.error); process.exit(1); }
  sent += fills.length;
  console.log(`${date}: ${fills.length} fills${j.warnings.length ? `, ${j.warnings.length} warnings` : ''}`);
}
console.log(`Sent ${sent} made-up fills. Open the journal to see them.`);
